"""Regenerate the paper and manifest tables in README.md and CORRESPONDENCE.md.

Both documents restate what `ledger/manifest.yaml` already records: how many
nodes exist, what state each is in, and where in the paper each one comes from.
Restated facts go stale.  Everything between a BEGIN/END marker pair below is
generated from the manifest, so the prose in those files never disagrees with
the checker again.

    python3 tools/sync_docs.py            # check, exit 1 if a block is stale
    python3 tools/sync_docs.py --write    # regenerate the blocks in place
"""

from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("sync_docs.py: PyYAML is required (pip install pyyaml)")

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "ledger" / "manifest.yaml"

SURFACE_BEGIN = "<!-- FROZEN-SURFACE-BEGIN (generated by tools/sync_docs.py) -->"
SURFACE_END = "<!-- FROZEN-SURFACE-END -->"
STATUS_BEGIN = "<!-- STATUS-BEGIN (generated by tools/sync_docs.py) -->"
STATUS_END = "<!-- STATUS-END -->"
MAP_BEGIN = "<!-- PAPER-MAP-BEGIN (generated by tools/sync_docs.py) -->"
MAP_END = "<!-- PAPER-MAP-END -->"

LABEL_RE = re.compile(r"label ([A-Za-z][A-Za-z0-9:_-]*)")
RANGE_RE = re.compile(r"orrw\.tex:\d+-\d+")


def lean_link(node: dict) -> str:
    """Link to the declaration itself, keeping line numbers derived data."""
    text = (ROOT / node["file"]).read_text(encoding="utf-8")
    matches = list(re.finditer(
        rf"^theorem\s+{re.escape(node['export'])}(?=\s|\{{|\()", text, re.M))
    if len(matches) != 1:
        raise LookupError(f"expected one declaration of {node['export']}")
    line = text.count("\n", 0, matches[0].start()) + 1
    return f"[{node['export']}]({node['file']}#L{line})"


def paper_cell(source: str) -> str:
    """Link a paper label or passage; retain supporting statements' roles."""
    rng = RANGE_RE.search(source)
    lab = LABEL_RE.search(source)
    if rng and lab:
        line = rng.group(0).split(":")[1].split("-")[0]
        return f"[{lab.group(1)}](paper/orrw.tex#L{line})"
    if rng:
        line = rng.group(0).split(":")[1].split("-")[0]
        return source.replace(rng.group(0), f"[paper passage](paper/orrw.tex#L{line})")
    if "prop:displacement" in source:
        line = paper_statements()["prop:displacement"]["line"]
        return f"[prop:displacement](paper/orrw.tex#L{line}), almost-sure clause"
    return source


def surface_table(nodes: list[dict]) -> str:
    rows = ["| id | Lean | paper | state |", "|---|---|---|---|"]
    for n in nodes:
        rows.append(
            f"| `{n['id']}` | {lean_link(n)} | {paper_cell(n['source'])} "
            f"| {n['state']} |")
    return "\n".join(rows)


def status_block(nodes: list[dict]) -> str:
    counts = Counter(n["state"] for n in nodes)
    parts = ", ".join(f"{counts[s]} `{s}`" for s in sorted(counts))
    draft = [n["id"] for n in nodes if n["state"] == "DRAFT_SORRY"]
    # State what is actually true.  Claiming a clean axiom closure while a
    # `DRAFT_SORRY` node exists is exactly the drift these blocks exist to stop.
    if draft:
        which = ", ".join(f"`{i}`" for i in draft)
        body = (
            f"The {len(nodes) - len(draft)} sealed nodes are machine-checked and no\n"
            f"sealed node's axiom closure contains `sorryAx`.  Still open: {which},\n"
            f"whose statement is frozen and whose proof is a registered `sorry`.")
    else:
        body = (
            "Every node's proof is machine-checked and its axiom closure contains\n"
            "no `sorryAx`.")
    return (
        f"Status: **{len(nodes)} frozen nodes — {parts}.**  {body}  Run\n"
        f"`python3 tools/check_axioms.py` to confirm.  Counts here are generated\n"
        f"from `ledger/manifest.yaml` by `python3 tools/sync_docs.py`; do not\n"
        f"edit them by hand and do not trust a count in prose that the checkers\n"
        f"have not confirmed.")


def paper_statements() -> dict[str, dict]:
    """Read titles, locations and the counters used by this manuscript."""
    paper = (ROOT / "paper" / "orrw.tex").read_text(encoding="utf-8")
    # Preserve newlines, so comments cannot change source links or counters.
    paper = re.sub(r"(?<!\\)%[^\n]*", "", paper)
    env = (r"\\begin\{(theorem|lemma|proposition|corollary|equation)\}"
           r"(?:\[([^\]]*)\])?\s*\\label\{([^}]+)\}")
    out, sec, seq, eq = {}, 0, 0, 0
    for m in re.finditer(r"\\section\{|" + env, paper):
        if m.group(0).startswith("\\section"):
            sec += 1
            seq = 0
        else:
            kind, title, label = m.groups()
            if label in out:
                raise LookupError(f"duplicate paper label {label}")
            if kind == "equation":
                eq += 1
                number = str(eq)
            else:
                seq += 1
                number = f"{sec}.{seq}"
            out[label] = dict(kind=kind, number=number, title=title or "",
                              line=paper.count("\n", 0, m.start()) + 1)
    expected = len(re.findall(
        r"\\begin\{(?:theorem|lemma|proposition|corollary|equation)\}", paper))
    if len(out) != expected:
        raise LookupError("a numbered paper environment has no readable label")
    return out


