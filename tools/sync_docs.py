def paper_map(nodes: list[dict]) -> str:
    """Link every paper result to its Lean declarations, in paper order."""
    statements = paper_statements()
    rows = ["| Paper result and label | Lean statement | Correspondence note |",
            "|---|---|---|"]
    entries, extra, covered = [], [], set()
    for n in nodes:
        if n["id"] in SUPPORT_ROLES:
            extra.append(n)
            continue
        lab = LABEL_RE.search(n["source"])
        label = lab.group(1) if lab else {
            "ae-range": "thm:whp", "ae-displacement": "prop:displacement",
        }[n["id"]]
        s = statements[label]
        covered.add(label)
        line, title = s["line"], s["title"]
        name = f"{s['kind'].capitalize()} {s['number']}"
        if n["id"] == "ae-range":
            paper_lines = (ROOT / "paper/orrw.tex").read_text().splitlines()
            end = next(i for i in range(line, len(paper_lines))
                       if r"\end{theorem}" in paper_lines[i])
            line = next(i + 1 for i in range(end + 1, len(paper_lines))
                        if paper_lines[i].strip())
            name = "After " + name
            title = "Almost-sure range lower bound"
        elif n["id"] == "guard-edges-le-sites":
            title = "Traversed edges bounded by visited sites"
        cell = (f"[{name}](paper/orrw.tex#L{line}): {title}"
                f"<br>`{label}`")
        note = NOTES.get(n["id"], "")
        entries.append((line, f"| {cell} | {lean_link(n)} | {note} |"))
    missing = {label for label, s in statements.items()
               if s["kind"] != "equation"} - covered
    if missing:
        raise LookupError(f"paper results missing from the map: {sorted(missing)}")
    rows.extend(row for _, row in sorted(entries, key=lambda entry: entry[0]))
    if extra:
        rows.append("")
        rows.append("The following supporting statements establish properties of "
                    "the formal model and have no separately stated paper result.")
        rows.append("")
        rows.append("| Role | Lean statement |")
        rows.append("|---|---|")
        for n in extra:
            rows.append(f"| {SUPPORT_ROLES[n['id']]} | {lean_link(n)} |")
    return "\n".join(rows)


def splice(text: str, begin: str, end: str, body: str) -> str:
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < 0:
        raise LookupError(f"missing marker pair {begin!r}")
    return text[:i] + begin + "\n\n" + body + "\n\n" + text[j:]


def main() -> int:
    write = "--write" in sys.argv[1:]
    nodes = (yaml.safe_load(MANIFEST.read_text(encoding="utf-8")) or {}).get("nodes") or []

    try:
        targets = [
            (ROOT / "CORRESPONDENCE.md", SURFACE_BEGIN, SURFACE_END, surface_table(nodes)),
            (ROOT / "README.md", STATUS_BEGIN, STATUS_END, status_block(nodes)),
            (ROOT / "README.md", MAP_BEGIN, MAP_END, paper_map(nodes)),
        ]
    except (LookupError, KeyError) as exc:
        print(f"sync_docs: {exc}", file=sys.stderr)
        return 2

    original, updated = {}, {}
    for path, begin, end, body in targets:
        if path not in original:
            original[path] = path.read_text(encoding="utf-8")
        text = updated.get(path, original[path])
        try:
            want = splice(text, begin, end, body)
        except LookupError as exc:
            print(f"sync_docs: {path.name}: {exc}", file=sys.stderr)
            return 2
        updated[path] = want

    stale = [(path, want) for path, want in updated.items()
             if want != original[path]]

    if not stale:
        print(f"sync_docs: OK ({len(nodes)} nodes; README.md and "
              f"CORRESPONDENCE.md agree with the manifest)")
        return 0

    for path, want in stale:
        print(f"  stale: {path.relative_to(ROOT)}")
        if write:
            path.write_text(want, encoding="utf-8")

    if not write:
        print("\nsync_docs: rerun with --write to regenerate", file=sys.stderr)
        return 1
    print(f"\nsync_docs: regenerated {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
